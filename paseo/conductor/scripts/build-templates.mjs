// Embeds templates/*.html into the server bundle: Paseo bundles plugin code, so the server
// cannot read files next to its source at runtime. Run `npm run templates` after editing them.
import { readdir, readFile, writeFile } from "node:fs/promises";

const dir = new URL("../templates/", import.meta.url);
const names = (await readdir(dir))
  .filter((name) => name.endsWith(".html"))
  .sort();
const entries = await Promise.all(
  names.map(async (name) => [name, await readFile(new URL(name, dir), "utf8")]),
);
const body = entries
  .map(([name, html]) => `  ${JSON.stringify(name)}: ${JSON.stringify(html)},`)
  .join("\n");
await writeFile(
  new URL("../server/templates.generated.ts", import.meta.url),
  `// Generated by scripts/build-templates.mjs from templates/*.html. Do not edit.\nexport const TEMPLATES: Record<string, string> = {\n${body}\n};\n`,
);
