// Bundles Pierre's DOM components (diffs + trees, Highlights backend only) into one script that the
// daemon serves to web and desktop clients on demand. Phones never load it. Run: `npm run build:web`.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

// The Highlights backend needs none of Shiki's grammars, themes or WebAssembly engine; they are most of the size.
const SHIKI_STUBS = {
  "shiki/langs": "export const bundledLanguages = {}; export const bundledLanguagesAlias = {};",
  "shiki/themes": "export const bundledThemes = {};",
  "shiki/wasm": "export default {};",
  "shiki/engine/oniguruma":
    "export const createOnigurumaEngine = () => { throw new Error('shiki-wasm is not bundled'); };",
};

const stubShiki = {
  name: "stub-shiki-assets",
  setup(api) {
    api.onResolve({ filter: /^shiki\/(langs|themes|wasm|engine\/oniguruma)$/ }, (args) => ({
      path: args.path,
      namespace: "shiki-stub",
    }));
    api.onLoad({ filter: /.*/, namespace: "shiki-stub" }, (args) => ({
      contents: SHIKI_STUBS[args.path],
      loader: "js",
    }));
  },
};

const result = await build({
  entryPoints: [`${root}scripts/web/entry.ts`],
  bundle: true,
  minify: true,
  write: false,
  platform: "browser",
  format: "iife",
  globalName: "PrismPierre",
  target: "es2020",
  plugins: [stubShiki],
  logLevel: "warning",
});
const code = result.outputFiles[0].text;
writeFileSync(
  `${root}server/web-bundle.generated.ts`,
  `// Generated by scripts/build-web.mjs. Do not edit.\nexport const WEB_BUNDLE = ${JSON.stringify(code)};\n`,
);
console.log(`web bundle: ${(code.length / 1e6).toFixed(2)} MB`);
